<h2>2. Welche Daten verarbeiten wir?</h2>

<h3>Zufällige Sitzungs-ID</h3>
<p>Beim Besuch der App wird automatisch eine zufällige, eindeutige Kennung (ID) in deinem Browser erstellt und lokal gespeichert. Diese ID:</p>
<ul>
	<li>wird nicht mit deiner Identität verknüpft</li>
	<li>ist nicht einsehbar für unsere Server, solange du nichts meldest</li>
	<li>wird gelöscht, wenn du deinen Browser schließt oder deinen lokalen Speicher löschst</li>
	<li>dient ausschließlich der Vermeidung von Spam und Missbrauch</li>
</ul>

<h3>Meldungsdaten</h3>
<p>Wenn du einen Punkt auf der Karte meldest, übermitteln wir an unsere Server:</p>
<ul>
	<li>Geografische Koordinaten des gewählten Kartenpunkts</li>
	<li>Zeitstempel der Meldung</li>
	<li>Lautstärkeinformation (falls angegeben)</li>
	<li>Deine anonyme Sitzungs-ID (zur Spam-Vermeidung)</li>
</ul>

<p><strong>Wichtig:</strong> Es handelt sich hierbei <strong>nicht</strong> um deine tatsächliche Nutzerposition, sondern um einen von dir frei gewählten Punkt auf der Karte.</p>

<h3>Keine weiteren Daten</h3>
<p>Wir erfassen nicht: Name, E-Mail, Telefonnummer, Browser-Daten, IP-Adresse oder sonstige identifizierende Informationen. Wir verwenden keine Cookies oder Tracking-Technologien.</p>

<h2>3. Zweck der Datenverarbeitung</h2>
<ul>
	<li><strong>Spam- und Missbrauchsprävention:</strong> Die anonyme ID schützt unseren Service vor automatisiertem Missbrauch</li>
	<li><strong>Sicherstellung der Funktionsfähigkeit:</strong> Technische Verarbeitung deiner Meldungen</li>
	<li><strong>Verarbeitung und Auswertung:</strong> Analyse der gemeldeten Punkte zur Verbesserung der App</li>
</ul>

